export type IconName = keyof typeof icons;

interface LucideIconProps extends LucideProps {
  name: string;
}

export function LucideIcon({ name, ...props }: LucideIconProps) {
  const Icon = icons[name as IconName];
  if (!Icon) return null;
  return <Icon {...props} />;
}
